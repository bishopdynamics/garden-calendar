#!/usr/bin/env python3
"""Fetch a photo for each crop from Wikipedia, store it locally, and write data.js.

Re-run safely: images already present in ../images are not re-downloaded.
Use IMAGE_OVERRIDES to force a specific Wikimedia Commons file for a crop.
"""
import json, re, subprocess, sys, time, urllib.parse, urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from crops import CROPS

ROOT = Path(__file__).resolve().parent.parent
IMG = ROOT / "images"
IMG.mkdir(exist_ok=True)
UA = "GardenCalendarPersonal/1.0 (offline personal garden planner)"

# crop id -> Commons file name, for pages whose lead image isn't a good photo
IMAGE_OVERRIDES = json.loads((Path(__file__).parent / "overrides.json").read_text()) \
    if (Path(__file__).parent / "overrides.json").exists() else {}


def get_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.load(r)
        except Exception as e:
            if attempt == 3:
                raise
            time.sleep(2 * (attempt + 1))


def download(url, dest):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        dest.write_bytes(r.read())


def strip_html(s):
    return re.sub(r"<[^>]+>", "", s or "").strip()


def commons_info(filename):
    q = urllib.parse.urlencode({
        "action": "query", "format": "json", "prop": "imageinfo",
        "titles": "File:" + filename, "iiprop": "url|extmetadata", "iiurlwidth": 800,
    })
    data = get_json("https://commons.wikimedia.org/w/api.php?" + q)
    page = next(iter(data["query"]["pages"].values()))
    ii = page["imageinfo"][0]
    md = ii.get("extmetadata", {})
    return {
        "thumb": ii.get("thumburl") or ii["url"],
        "artist": strip_html(md.get("Artist", {}).get("value")),
        "license": strip_html(md.get("LicenseShortName", {}).get("value")),
        "source": ii.get("descriptionurl"),
    }


def main():
    credits_path = Path(__file__).parent / "credits.json"
    credits = json.loads(credits_path.read_text()) if credits_path.exists() else {}
    for c in CROPS:
        cid = c["id"]
        dest = IMG / f"{cid}.jpg"
        override = IMAGE_OVERRIDES.get(cid)
        if dest.exists() and cid in credits and credits[cid].get("file") == (override or credits[cid].get("file")):
            continue
        try:
            if override:
                filename = override
            else:
                s = get_json("https://en.wikipedia.org/api/rest_v1/page/summary/"
                             + urllib.parse.quote(c["wiki"].replace(" ", "_")))
                src = (s.get("originalimage") or s.get("thumbnail") or {}).get("source")
                if not src:
                    print(f"!! no image for {cid}")
                    continue
                parts = src.split("?")[0].split("/")
                # thumb URLs end in .../File.jpg/NNNpx-File.jpg
                filename = urllib.parse.unquote(parts[-2] if "/thumb/" in src else parts[-1])
            info = commons_info(filename)
            tmp = IMG / f"{cid}.src"
            download(info["thumb"], tmp)
            # normalize: flatten transparency, max 800px wide, compressed JPEG
            subprocess.run(["convert", str(tmp) + "[0]", "-background", "white", "-flatten",
                            "-resize", "800x800>", "-quality", "82", "-strip", str(dest)], check=True)
            tmp.unlink()
            credits[cid] = {"file": filename, **{k: info[k] for k in ("artist", "license", "source")}}
            print(f"ok {cid}: {filename}")
            time.sleep(0.3)
        except Exception as e:
            print(f"!! {cid}: {e}")
    credits_path.write_text(json.dumps(credits, indent=1))

    out = []
    for c in CROPS:
        d = {k: c[k] for k in ("id", "name", "cat", "season", "days", "sun", "spacing", "tips", "wiki", "hydro", "hydro_note", "rule")}
        d["localTips"] = c.get("localTips", {})
        cr = credits.get(c["id"])
        d["img"] = f"images/{c['id']}.jpg" if cr and (IMG / f"{c['id']}.jpg").exists() else None
        d["credit"] = cr
        out.append(d)
    (ROOT / "data.js").write_text("// Generated by build/build.py — edit build/crops.py instead.\n"
                                  "window.CROPS = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False).replace('},{"id"', '},\n{"id"') + ";\n")
    print(f"wrote data.js with {len(out)} crops")


if __name__ == "__main__":
    main()
