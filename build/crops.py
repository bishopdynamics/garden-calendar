# Crop definitions for the location-aware garden calendar (continental US).
#
# Planting/harvest months are NOT stored here: engine.js computes them for each location from
# NOAA climate normals (frost dates + monthly temperatures) using each crop's `rule`.
#
# Rule kinds
#   annual     : evaluated on every candidate planting date. Temperatures are °F daily normals.
#                hardy      0 tender (no frost) · 1 half-hardy (light frost OK, not 28°F) ·
#                           2 hardy (mean lows ≥ 26°F while growing) · 3 very hardy (mean lows ≥ 18°F)
#                methods    "sow" (direct) / "transplant" (with `lead` weeks indoors) / "plant" (tubers, slips, sets)
#                tPlant     [min, max] average temperature on the planting date (soil-temperature proxy)
#                days       [min, max] days to maturity (from transplant, or from sowing + `germ`)
#                span       how many days harvest continues
#                growMin    mean temperature needed while growing
#                heatMax    cool crops: mean high near maturity above which they bolt / turn bitter
#                heatMin    heat lovers: mean high in the second half of growth needed to ripen
#                fruitHeatMax  fruit set fails when the month before maturity averages hotter than this
#   overwinter : fall-planted, harvested the next summer (garlic). plantTavg = falling temps window.
#   perennial  : zones [min, max] hardiness range; plantType bareroot | evergreen | container;
#                harvest = fixed months, or N days after spring bloom, or while temps are in a range.
#   variants   : [{minZone, rule}] overrides for warmer zones; annualElse = rule used below the zone range.
#
# localTips: extra advice shown when it applies — hot (40+ days ≥ 90°F), short (frost-free < 150 days),
#            cold (zone < 6), mild (zone ≥ 9).

VEG, FRUIT, HERB = "vegetable", "fruit", "herb"
COOL, WARM, PEREN = "cool", "warm", "perennial"


def warm(methods, tPlant, days, span, **kw):
    return dict(kind="annual", hardy=0, methods=methods, tPlant=tPlant, days=days, span=span, **kw)


def cool(hardy, methods, tPlant, days, span, **kw):
    return dict(kind="annual", hardy=hardy, methods=methods, tPlant=tPlant, days=days, span=span, **kw)


def peren(zones, plantType, harvest, **kw):
    return dict(kind="perennial", zones=zones, plantType=plantType, harvest=harvest, **kw)


def bloom(d0, d1, t=50):
    return dict(type="bloom", days=[d0, d1], bloomT=t)


def fixed(*months):
    return dict(type="fixed", months=list(months))


def temp(lo, hi, **kw):
    return dict(type="temp", tavg=[lo, hi], **kw)


